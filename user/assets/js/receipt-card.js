/* Yareema Data Hub — styled receipt card (matches the mobile app)
 * Drop-in: include this file + html2canvas + jspdf, then call
 *   openReceiptCard(transactionObject, event)
 * from the "Receipt" button. No markup changes required — the modal is
 * created on demand.
 *
 * CDN deps (add once, before this script):
 *   <script src="https://cdnjs.cloudflare.com/ajax/libs/html2canvas/1.4.1/html2canvas.min.js"></script>
 *   <script src="https://cdnjs.cloudflare.com/ajax/libs/jspdf/2.5.1/jspdf.umd.min.js"></script>
 */
(function () {
  const LOGO_SRC = (window.YR_RECEIPT_LOGO || 'assets/images/logo.png');
  const NAVY = '#1e3d5c';
  let current = null;

  function esc(v) {
    return String(v == null ? 'N/A' : v).replace(/[<>&]/g, (c) => ({ '<': '&lt;', '>': '&gt;', '&': '&amp;' }[c]));
  }
  function naira(v) {
    return '₦' + Math.abs(Number(v || 0)).toLocaleString('en-US', { minimumFractionDigits: 2 });
  }
  function statusInfo(t) {
    const s = String(t.status || t.paymentStatus || '').toUpperCase();
    if (s === 'FAILED') return { label: 'Failed', color: '#dc2626', bg: '#fef2f2' };
    if (s === 'PENDING' || s === 'PROCESSING') return { label: 'Pending', color: '#d97706', bg: '#fffbeb' };
    return { label: s ? (s.charAt(0) + s.slice(1).toLowerCase()) : 'Successful', color: '#16a34a', bg: '#dcfce7' };
  }

  function cardHTML(t) {
    const st = statusInfo(t);
    const date = t.createdAt ? new Date(t.createdAt).toLocaleString('en-NG', { dateStyle: 'medium', timeStyle: 'short' }) : 'N/A';
    const rows = [
      ['Type', t.type],
      ['Reference', t.reference || t.transactionReference],
      ['Date', date],
      ['Description', t.description || t.paymentDescription],
    ];
    const tokenBlock = t.token
      ? `<div style="margin-top:18px;background:#ecfdf5;border-radius:12px;padding:16px;text-align:center;">
           <div style="font-size:12px;color:#475569;margin-bottom:6px;">⚡ Electricity Token</div>
           <div style="font-size:18px;font-weight:800;letter-spacing:2px;color:#0f172a;word-break:break-all;">${esc(t.token)}</div>
         </div>`
      : '';
    return `
      <div id="yrReceiptCard" style="background:#fff;border-radius:20px;padding:28px 24px;max-width:380px;margin:0 auto;font-family:'Inter',-apple-system,Segoe UI,Roboto,sans-serif;">
        <div style="text-align:center;">
          <img src="${LOGO_SRC}" alt="Yareema" crossorigin="anonymous" style="width:70px;height:65px;border-radius:14px;object-fit:contain;margin:0 auto;"/>
          <div style="font-size:18px;font-weight:800;color:${NAVY};margin-top:8px;">Yareema Data Hub</div>
          <div style="display:inline-flex;align-items:center;gap:6px;margin-top:12px;padding:5px 14px;border-radius:999px;background:${st.bg};color:${st.color};font-size:13px;font-weight:700;">
            ${st.label}
          </div>
          <div style="font-size:30px;font-weight:800;color:#0f172a;margin-top:14px;">${naira(t.amount)}</div>
        </div>
        <div style="height:1px;background:#e2e8f0;margin:20px 0;"></div>
        <table style="width:100%;border-collapse:collapse;">
          ${rows.map(([l, v]) => `<tr>
            <td style="padding:9px 0;color:#64748b;font-size:13px;vertical-align:top;">${l}</td>
            <td style="padding:9px 0;color:#0f172a;font-size:13px;font-weight:600;text-align:right;">${esc(v)}</td>
          </tr>`).join('')}
        </table>
        ${tokenBlock}
        <div style="text-align:center;margin-top:22px;color:#94a3b8;font-size:11px;">Generated by Yareema Data Hub • Thank you for your patronage</div>
      </div>`;
  }

  function ensureModal() {
    let modal = document.getElementById('yrReceiptModal');
    if (modal) return modal;
    modal = document.createElement('div');
    modal.id = 'yrReceiptModal';
    modal.style.cssText = 'display:none;position:fixed;inset:0;background:rgba(15,23,42,0.7);z-index:2000;align-items:center;justify-content:center;padding:16px;';
    modal.innerHTML = `
      <div style="background:#f8fafc;border-radius:20px;max-width:430px;width:100%;max-height:92vh;overflow-y:auto;padding:18px;">
        <div id="yrReceiptHost"></div>
        <div style="display:flex;gap:8px;margin-top:16px;">
          <button id="yrShareBtn" style="flex:1;display:flex;flex-direction:column;align-items:center;gap:4px;padding:11px;border:1.5px solid #e2e8f0;border-radius:12px;background:#fff;color:${NAVY};font-weight:600;font-size:12px;cursor:pointer;">
            <i data-lucide="share-2" style="width:18px;height:18px;"></i>Share</button>
          <button id="yrImgBtn" style="flex:1;display:flex;flex-direction:column;align-items:center;gap:4px;padding:11px;border:1.5px solid #e2e8f0;border-radius:12px;background:#fff;color:${NAVY};font-weight:600;font-size:12px;cursor:pointer;">
            <i data-lucide="image" style="width:18px;height:18px;"></i>Save Image</button>
          <button id="yrPdfBtn" style="flex:1;display:flex;flex-direction:column;align-items:center;gap:4px;padding:11px;border:1.5px solid #e2e8f0;border-radius:12px;background:#fff;color:${NAVY};font-weight:600;font-size:12px;cursor:pointer;">
            <i data-lucide="file-text" style="width:18px;height:18px;"></i>PDF</button>
        </div>
        <button id="yrCloseBtn" style="width:100%;margin-top:10px;padding:13px;border:none;border-radius:12px;background:${NAVY};color:#fff;font-weight:700;font-size:15px;cursor:pointer;">Close</button>
      </div>`;
    document.body.appendChild(modal);
    modal.addEventListener('click', (e) => { if (e.target === modal) closeReceiptCard(); });
    modal.querySelector('#yrCloseBtn').onclick = closeReceiptCard;
    modal.querySelector('#yrShareBtn').onclick = shareReceiptImage;
    modal.querySelector('#yrImgBtn').onclick = saveReceiptImage;
    modal.querySelector('#yrPdfBtn').onclick = downloadReceiptPDF;
    return modal;
  }

  async function snapshot() {
    const node = document.getElementById('yrReceiptCard');
    if (!node || typeof html2canvas === 'undefined') throw new Error('Receipt not ready');
    return html2canvas(node, { scale: 2, backgroundColor: '#ffffff', useCORS: true });
  }
  function fileName(ext) {
    const ref = (current && (current.reference || current.transactionReference || current.id || current._id)) || Date.now();
    return `Yareema-Receipt-${String(ref).slice(-10)}.${ext}`;
  }
  function canvasToBlob(canvas) {
    return new Promise((res) => canvas.toBlob(res, 'image/png', 1));
  }

  async function saveReceiptImage() {
    try {
      const canvas = await snapshot();
      const blob = await canvasToBlob(canvas);
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url; a.download = fileName('png');
      document.body.appendChild(a); a.click(); a.remove();
      URL.revokeObjectURL(url);
    } catch (e) { alert(e.message || 'Could not save image'); }
  }

  async function shareReceiptImage() {
    try {
      const canvas = await snapshot();
      const blob = await canvasToBlob(canvas);
      const file = new File([blob], fileName('png'), { type: 'image/png' });
      if (navigator.canShare && navigator.canShare({ files: [file] })) {
        await navigator.share({ files: [file], title: 'Yareema Receipt', text: 'My transaction receipt' });
      } else {
        await saveReceiptImage(); // fallback: download
      }
    } catch (e) {
      if (e && e.name === 'AbortError') return; // user cancelled
      alert(e.message || 'Could not share receipt');
    }
  }

  async function downloadReceiptPDF() {
    try {
      const canvas = await snapshot();
      const img = canvas.toDataURL('image/png', 1);
      const jsPDFCtor = (window.jspdf && window.jspdf.jsPDF) || window.jsPDF;
      if (!jsPDFCtor) { // fallback to print dialog
        const w = window.open('', '_blank');
        w.document.write(`<html><head><title>Receipt</title></head><body style="margin:0;padding:20px;text-align:center;"><img src="${img}" style="max-width:100%"/></body></html>`);
        w.document.close(); w.focus(); setTimeout(() => w.print(), 350);
        return;
      }
      const pdf = new jsPDFCtor({ orientation: 'p', unit: 'pt', format: 'a4' });
      const pw = pdf.internal.pageSize.getWidth();
      const margin = 40;
      const imgW = pw - margin * 2;
      const imgH = (canvas.height / canvas.width) * imgW;
      pdf.addImage(img, 'PNG', margin, margin, imgW, imgH);
      pdf.save(fileName('pdf'));
    } catch (e) { alert(e.message || 'Could not create PDF'); }
  }

  window.openReceiptCard = function (t, event) {
    if (event && event.stopPropagation) event.stopPropagation();
    current = t || {};
    const modal = ensureModal();
    modal.querySelector('#yrReceiptHost').innerHTML = cardHTML(current);
    modal.style.display = 'flex';
    if (window.lucide && lucide.createIcons) lucide.createIcons();
  };
  window.closeReceiptCard = function () {
    const modal = document.getElementById('yrReceiptModal');
    if (modal) modal.style.display = 'none';
    current = null;
  };
})();